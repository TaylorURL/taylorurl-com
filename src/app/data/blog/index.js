/**
 * Every article, newest first, each carrying the series it belongs to. The
 * membership is joined on here rather than written into the article files, so
 * an article's own file holds only its words.
 */
export const BLOG_POSTS = ALL_POSTS.map(post => ({
  ...post,
  series: POST_SERIES[post.slug] || null,
})).sort((a, b) => new Date(b.date) - new Date(a.date))

/**
 * The series that have something in them, newest article first inside each.
 * A series with no article yet is defined but not published: the register can
 * name where the writing is going before any of it has been written, and the
 * blog only ever shows a reader a shelf with something on it.
 */
export const BLOG_SERIES_INDEX = BLOG_SERIES.map(series => ({
  ...series,
  posts: BLOG_POSTS.filter(post => post.series === series.slug),
})).filter(series => series.posts.length > 0)

export function findSeries(slug) {
  return BLOG_SERIES_INDEX.find(series => series.slug === slug) || null
}

/**
 * The articles to read after this one. The rest of its series comes first,
 * because that is the thread the reader is already following; the shelf is
 * topped up from the same category when the series is short, so a new series
 * still ends its articles with somewhere to go.
 */
export function relatedPosts(post, limit = 3) {
  if (!post) return []
  const sameSeries = BLOG_POSTS.filter(
    other => other.slug !== post.slug && other.series && other.series === post.series
  )
  const sameCategory = BLOG_POSTS.filter(
    other =>
      other.slug !== post.slug &&
      other.category === post.category &&
      !sameSeries.some(seriesPost => seriesPost.slug === other.slug)
  )
  return [...sameSeries, ...sameCategory].slice(0, limit)
}
